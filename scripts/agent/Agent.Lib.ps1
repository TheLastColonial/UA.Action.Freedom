function Read-SlotRegistry {
    param([Parameter(Mandatory)][string]$Path)

    $registry = @{}
    if (-not (Test-Path $Path)) { return $registry }

    $raw = Get-Content $Path -Raw
    if ([string]::IsNullOrWhiteSpace($raw)) { return $registry }

    $parsed = $raw | ConvertFrom-Json -AsHashtable
    foreach ($name in $parsed.Keys) { $registry[$name] = $parsed[$name] }
    $registry
}

function Write-SlotRegistry {
    param(
        [Parameter(Mandatory)][string]$Path,
        [Parameter(Mandatory)][hashtable]$Registry
    )

    $Registry | ConvertTo-Json -Depth 5 | Set-Content -Path $Path -Encoding utf8
}

function Use-SlotRegistryLock {
    param(
        [Parameter(Mandatory)][string]$Path,
        [Parameter(Mandatory)][scriptblock]$Action
    )

    $lockPath = "$Path.lock"
    $stream = $null
    foreach ($attempt in 1..50) {
        try {
            $stream = [System.IO.File]::Open($lockPath, 'OpenOrCreate', 'ReadWrite', 'None')
            break
        } catch [System.IO.IOException] {
            Start-Sleep -Milliseconds 200
        }
    }
    if ($null -eq $stream) { throw "Could not lock $lockPath; is another agent.ps1 running?" }

    try { & $Action } finally { $stream.Dispose() }
}

function Test-PortFree {
    param([Parameter(Mandatory)][int]$Port)

    $listener = [System.Net.Sockets.TcpListener]::new([System.Net.IPAddress]::Any, $Port)
    try { $listener.Start(); $true } catch { $false } finally { $listener.Stop() }
}
