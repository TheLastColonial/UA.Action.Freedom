function Get-AgentPorts {
    param([Parameter(Mandatory)][int]$Slot)

    if ($Slot -lt 0 -or $Slot -gt $script:MaxSlot) {
        throw "Slot must be 0-$($script:MaxSlot), got $Slot."
    }

    $ports = [ordered]@{}
    foreach ($key in $script:PortOffsets.Keys) {
        $ports[$key] = if ($Slot -eq 0) { $script:MainPorts[$key] } else { 20000 + $Slot * 100 + $script:PortOffsets[$key] }
    }
    $ports
}

