function Get-AgentTestVariables {
    param(
        [Parameter(Mandatory)][int]$Slot,
        [Parameter(Mandatory)][hashtable]$Passwords,
        [string]$HostName = 'localhost',
        [string]$StorageHost = '127.0.0.1',
        [bool]$RequireIntegration = $true
    )

    $p = Get-AgentPorts -Slot $Slot
    $sql = { param($user, $pw) "Server=$HostName,$($p.MSSQL_PORT);Database=Freedom;User Id=$user;Password=$pw;TrustServerCertificate=True;Encrypt=False;Connect Timeout=3" }
    # An IP, never a hostname: on a non-default port the Azure SDK only treats an IP endpoint as
    # path-style, and otherwise drops the container from the blob URL (ContainerNotFound).
    $storage = "DefaultEndpointsProtocol=http;AccountName=devstoreaccount1;AccountKey=$($script:AzuriteKey);" +
        "BlobEndpoint=http://$StorageHost`:$($p.AZURITE_BLOB_PORT)/devstoreaccount1;" +
        "QueueEndpoint=http://$StorageHost`:$($p.AZURITE_QUEUE_PORT)/devstoreaccount1;"

    $vars = [ordered]@{
        FREEDOM_BASE_URL                    = "http://${HostName}:$($p.EDGE_HTTP_PORT)"
        FREEDOM_OIDC_URL                    = "http://${HostName}:$($p.KEYCLOAK_PORT)/realms/freedom"
        PLAYWRIGHT_BASE_URL                 = "http://${HostName}:$($p.EDGE_HTTP_PORT)"
        VITE_API_PROXY_TARGET               = "http://${HostName}:$($p.EDGE_HTTP_PORT)"
        ConnectionStrings__Freedom          = & $sql 'freedom_app' $Passwords.App
        ConnectionStrings__FreedomSensitive = & $sql 'freedom_sensitive' $Passwords.Sensitive
        Storage__ConnectionString           = $storage
    }
    if ($RequireIntegration) { $vars['FREEDOM_REQUIRE_INTEGRATION'] = 'true' }
    $vars
}

function New-AgentTestEnv {
    param(
        [Parameter(Mandatory)][int]$Slot,
        [Parameter(Mandatory)][ValidateSet('powershell', 'sh')][string]$Shell,
        [Parameter(Mandatory)][hashtable]$Passwords,
        [string]$HostName = 'localhost',
        [string]$StorageHost = '127.0.0.1',
        [bool]$RequireIntegration = $true
    )

    $vars = Get-AgentTestVariables -Slot $Slot -Passwords $Passwords -HostName $HostName -StorageHost $StorageHost -RequireIntegration $RequireIntegration
    $header = "# generated by agent.ps1 (slot $Slot). Source it before dotnet test / playwright: " +
        $(if ($Shell -eq 'powershell') { '. ./.agent/env.ps1' } else { '. ./.agent/env.sh' })

    $lines = foreach ($key in $vars.Keys) {
        $value = $vars[$key].Replace("'", $(if ($Shell -eq 'powershell') { "''" } else { "'\''" }))
        if ($Shell -eq 'powershell') { "`$env:$key = '$value'" } else { "export $key='$value'" }
    }
    @($header) + @($lines)
}

function Test-StackMemoryBudget {
    param(
        [Parameter(Mandatory)][long]$TotalBytes,
        [Parameter(Mandatory)][int]$RunningStacks
    )

    (($RunningStacks + 1) * $script:StackMemoryBytes) -le $TotalBytes
}

