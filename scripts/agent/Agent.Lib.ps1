function Get-RegistrySlots {
    param([Parameter(Mandatory)]$Registry)

    $slots = @{}
    foreach ($name in $Registry.Keys) {
        $slots[$name] = [int]$Registry[$name].slot
    }
    $slots
}

function Select-AgentSlot {
    param(
        [Parameter(Mandatory)][hashtable]$Registry,
        [int]$Requested = 0
    )

    $taken = @{}
    foreach ($name in $Registry.Keys) { $taken[[int]$Registry[$name]] = $name }

    if ($Requested -gt 0) {
        if ($Requested -gt $script:MaxSlot) { throw "Slot must be 1-$($script:MaxSlot), got $Requested." }
        if ($taken.ContainsKey($Requested)) { throw "Slot $Requested is already used by '$($taken[$Requested])'." }
        return $Requested
    }

    foreach ($slot in 1..$script:MaxSlot) {
        if (-not $taken.ContainsKey($slot)) { return $slot }
    }
    throw "All $($script:MaxSlot) agent slots are in use (registry is full). Remove one with: agent.ps1 remove <name>"
}

function Get-ComposeFileLine {
    param([bool]$HotReload)
    if ($HotReload) { 'COMPOSE_FILE=docker-compose.yml:docker-compose.dev.yml' } else { 'COMPOSE_FILE=docker-compose.yml' }
}

function Set-EnvComposeFiles {
    param([Parameter(Mandatory)][AllowEmptyString()][string[]]$Lines, [Parameter(Mandatory)][bool]$HotReload)
    $Lines | ForEach-Object { if ($_ -like 'COMPOSE_FILE=*') { Get-ComposeFileLine -HotReload $HotReload } else { $_ } }
}

function New-AgentEnvContent {
    param(
        [Parameter(Mandatory)][AllowEmptyString()][string[]]$BaseLines,
        [Parameter(Mandatory)][string]$Name,
        [Parameter(Mandatory)][int]$Slot,
        [bool]$HotReload = $true
    )

    $ports = Get-AgentPorts -Slot $Slot
    $overridden = @('COMPOSE_PROJECT_NAME', 'FREEDOM_PREFIX', 'FREEDOM_IMAGE_TAG', 'KEYCLOAK_JAVA_HEAP', 'MSSQL_MEMORY_LIMIT_MB', 'COMPOSE_FILE', 'COMPOSE_PATH_SEPARATOR') + @($ports.Keys)

    $kept = $BaseLines | Where-Object {
        $key = ($_ -split '=', 2)[0].Trim()
        $overridden -notcontains $key
    }

    $generated = @(
        '',
        "# --- generated by agent.ps1 for '$Name' (slot $Slot); do not edit, re-run 'agent.ps1 new' ---",
        "COMPOSE_PROJECT_NAME=freedom-$Name",
        "FREEDOM_PREFIX=freedom-$Name",
        "FREEDOM_IMAGE_TAG=$Name",
        # So a bare `docker compose ps|down` in this worktree sees the same services agent.ps1 starts
        # (the Vite `web` service exists only in the dev file; without it `down` leaves it running).
        'COMPOSE_PATH_SEPARATOR=:',
        (Get-ComposeFileLine -HotReload $HotReload),
        # Keycloak and SQL Server are the two big ones; uncapped, three stacks exhaust a 16 GB Docker VM.
        "KEYCLOAK_JAVA_HEAP=`"$($script:AgentKeycloakHeap)`"",
        "MSSQL_MEMORY_LIMIT_MB=$($script:AgentMssqlLimitMb)"
    ) + @($ports.Keys | ForEach-Object { "$_=$($ports[$_])" })

    @($kept) + $generated
}

